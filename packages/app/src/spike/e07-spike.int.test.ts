  it("(c) tokens and cookies never cross instances (separate secrets, and also a shared one)", async () => {
    const ownerCookie = cookieOf(
      await http(owner, O("/sign-in/email"), { body: { email: OWNER_EMAIL, password: PASSWORD } }),
    );
    const customerCookie = cookieOf(
      await http(customer, C("/sign-in/email"), {
        body: { email: "alice@e07-spike.test", password: PASSWORD },
      }),
    );
    expect(ownerCookie).toMatch(/^better-auth\.session_token=/);
    expect(customerCookie).toMatch(/^commerceos-customer\.session_token=/);
    const ownerValue = ownerCookie.split("=").slice(1).join("=");
    const customerValue = customerCookie.split("=").slice(1).join("=");
    const swappedIntoCustomer = `commerceos-customer.session_token=${ownerValue}`;
    const swappedIntoOwner = `better-auth.session_token=${customerValue}`;

    // A shared-secret customer instance shows isolation does not rest on the secret alone.
    const sharedSecret = createCustomerAuth({
      pool,
      env: env({ CUSTOMER_AUTH_SECRET: OWNER_SECRET }),
      log: log("shared"),
    });
    const outcome = {
      ownerCookieOnCustomer: await customerSession(ownerCookie),
      customerCookieOnOwner: await ownerSession(customerCookie),
      ownerTokenUnderCustomerName: await customerSession(swappedIntoCustomer),
      customerTokenUnderOwnerName: await ownerSession(swappedIntoOwner),
      ownerTokenUnderCustomerNameSharedSecret: await customerSession(
        swappedIntoCustomer,
        sharedSecret,
      ),
      bothCookies: {
        customer: (await customerSession(`${ownerCookie}; ${customerCookie}`))?.user.email ?? null,
        owner: (await ownerSession(`${ownerCookie}; ${customerCookie}`))?.user.email ?? null,
      },
    };
    record("c", outcome);
    expect(outcome.ownerCookieOnCustomer).toBeNull();
    expect(outcome.customerCookieOnOwner).toBeNull();
    expect(outcome.ownerTokenUnderCustomerName).toBeNull();
    expect(outcome.customerTokenUnderOwnerName).toBeNull();
    expect(outcome.ownerTokenUnderCustomerNameSharedSecret).toBeNull();
    expect(outcome.bothCookies).toEqual({
      customer: "alice@e07-spike.test",
      owner: OWNER_EMAIL,
    });

    // The raw token (signature stripped) under the other name, with a valid signature from
    // the other instance's own secret, still finds no row in the other table.
    const ownerToken = decodeURIComponent(ownerValue).split(".")[0]!;
    const resigned = await customerSessionWithRawToken(ownerToken);
    // Positive control: the same re-signing of the customer's own token does resolve, so the
    // null above comes from the missing row, not from a wrong signature.
    const control = await customerSessionWithRawToken(
      decodeURIComponent(customerValue).split(".")[0]!,
    );
    record("c.ownerTokenResignedWithCustomerSecret", resigned);
    record("c.controlCustomerTokenResigned", control?.user.email ?? null);
    expect(resigned).toBeNull();
    expect(control?.user.email).toBe("alice@e07-spike.test");
  });

