/** Signs a raw owner token with the customer instance's own secret, then asks the customer instance. */
async function customerSessionWithRawToken(token: string) {
  const { makeSignature } = await import("better-auth/crypto");
  const signature = await makeSignature(token, CUSTOMER_SECRET);
  const value = encodeURIComponent(`${token}.${signature}`);
  return customer.api.getSession({
    headers: new Headers({ cookie: `commerceos-customer.session_token=${value}` }),
  });
}
